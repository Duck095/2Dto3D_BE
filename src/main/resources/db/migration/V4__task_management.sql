CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    description TEXT NOT NULL,
    priority VARCHAR(16) NOT NULL,
    assignee_staff_profile_id BIGINT NOT NULL,
    created_by_user_id INTEGER NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'ASSIGNED',
    assignment_cycle BIGINT NOT NULL DEFAULT 1,
    due_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_tasks_assignee FOREIGN KEY (assignee_staff_profile_id) REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    CONSTRAINT fk_tasks_creator FOREIGN KEY (created_by_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_tasks_title CHECK (BTRIM(title) <> ''),
    CONSTRAINT ck_tasks_description CHECK (BTRIM(description) <> ''),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT ck_tasks_status CHECK (status IN ('ASSIGNED', 'IN_PROGRESS', 'SUBMITTED', 'REVISION_REQUESTED', 'APPROVED')),
    CONSTRAINT ck_tasks_assignment_cycle CHECK (assignment_cycle >= 1),
    CONSTRAINT ck_tasks_version CHECK (version >= 0)
);
CREATE INDEX idx_tasks_assignee_status_due_id ON tasks (assignee_staff_profile_id, status, due_at, id);
CREATE INDEX idx_tasks_assignee_updated_id ON tasks (assignee_staff_profile_id, updated_at DESC, id DESC);
CREATE INDEX idx_tasks_status_due_id ON tasks (status, due_at, id);
CREATE INDEX idx_tasks_updated_id ON tasks (updated_at DESC, id DESC);

CREATE TABLE task_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    submission_number INTEGER NOT NULL,
    submitted_by_user_id INTEGER NOT NULL,
    submitted_by_staff_profile_id BIGINT NOT NULL,
    assignment_cycle BIGINT NOT NULL,
    result_description TEXT,
    result_url VARCHAR(2048),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_task_submissions_task FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_submissions_user FOREIGN KEY (submitted_by_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_submissions_staff FOREIGN KEY (submitted_by_staff_profile_id) REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    CONSTRAINT uq_task_submissions_number UNIQUE (task_id, submission_number),
    CONSTRAINT ck_task_submissions_number CHECK (submission_number >= 1),
    CONSTRAINT ck_task_submissions_cycle CHECK (assignment_cycle >= 1),
    CONSTRAINT ck_task_submissions_result CHECK (
        (result_description IS NOT NULL AND BTRIM(result_description) <> '') OR
        (result_url IS NOT NULL AND BTRIM(result_url) <> '')
    )
);
CREATE INDEX idx_task_submissions_task_cycle_time ON task_submissions (task_id, assignment_cycle, submitted_at DESC, id DESC);

CREATE TABLE task_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    actor_user_id INTEGER NOT NULL,
    assignment_cycle BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    previous_status VARCHAR(24),
    new_status VARCHAR(24),
    previous_assignee_staff_profile_id BIGINT,
    new_assignee_staff_profile_id BIGINT,
    submission_id BIGINT,
    note VARCHAR(2000),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_task_history_task FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_history_actor FOREIGN KEY (actor_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_history_previous_assignee FOREIGN KEY (previous_assignee_staff_profile_id) REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_history_new_assignee FOREIGN KEY (new_assignee_staff_profile_id) REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_history_submission FOREIGN KEY (submission_id) REFERENCES task_submissions(id) ON DELETE RESTRICT,
    CONSTRAINT ck_task_history_cycle CHECK (assignment_cycle >= 1),
    CONSTRAINT ck_task_history_action CHECK (action IN ('TASK_CREATED', 'TASK_UPDATED', 'TASK_REASSIGNED', 'TASK_STARTED', 'TASK_SUBMITTED', 'REVIEW_APPROVED', 'REVISION_REQUESTED')),
    CONSTRAINT ck_task_history_previous_status CHECK (previous_status IS NULL OR previous_status IN ('ASSIGNED', 'IN_PROGRESS', 'SUBMITTED', 'REVISION_REQUESTED', 'APPROVED')),
    CONSTRAINT ck_task_history_new_status CHECK (new_status IS NULL OR new_status IN ('ASSIGNED', 'IN_PROGRESS', 'SUBMITTED', 'REVISION_REQUESTED', 'APPROVED')),
    CONSTRAINT ck_task_history_note CHECK (note IS NULL OR CHAR_LENGTH(note) <= 2000)
);
CREATE INDEX idx_task_history_task_time ON task_history (task_id, occurred_at DESC, id DESC);
CREATE INDEX idx_task_history_task_cycle_time ON task_history (task_id, assignment_cycle, occurred_at DESC, id DESC);
CREATE INDEX idx_task_history_actor_time ON task_history (actor_user_id, occurred_at DESC);
