CREATE TABLE validated_slicing_runs (
    slicing_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id INTEGER NOT NULL REFERENCES model_3d(model_id) ON DELETE RESTRICT,
    material_id INTEGER NOT NULL REFERENCES materials(material_id) ON DELETE RESTRICT,
    printer_id INTEGER NOT NULL REFERENCES printers(printer_id) ON DELETE RESTRICT,
    configuration_fingerprint VARCHAR(128) NOT NULL,
    configuration_snapshot TEXT NOT NULL,
    consumed_material_grams NUMERIC(18, 6) NOT NULL CHECK (consumed_material_grams > 0),
    print_time_seconds BIGINT NOT NULL CHECK (print_time_seconds > 0),
    source VARCHAR(100) NOT NULL,
    validated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    validated BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_slicing_run_fingerprint CHECK (length(trim(configuration_fingerprint)) > 0),
    CONSTRAINT ck_slicing_run_source CHECK (length(trim(source)) > 0)
);

CREATE INDEX ix_validated_slicing_run_quote_lookup
    ON validated_slicing_runs(model_id, material_id, printer_id, configuration_fingerprint, validated_at DESC)
    WHERE validated = TRUE;

